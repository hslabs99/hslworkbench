#!/usr/bin/env node
/**
 * Generate a local dev `.env.local` for hsl-workbench from the non-secret
 * values already committed in `apphosting.yaml`.
 *
 * Rationale: local dev (`npm run dev`) reads FIREBASE_* / VITE_MS_* / SENDGRID_*
 * from `.env.local` (see server/loadLocalEnv.js and .env.example). The Firebase
 * web config and Microsoft client IDs are public values (they ship in the
 * browser bundle in production) and are the App Hosting BUILD/RUNTIME values in
 * apphosting.yaml, so mirroring them locally is safe and lets the app run
 * end-to-end against the same Firebase project a developer would use.
 *
 * Secret-backed values (OPENAI_API_KEY, SENDGRID_API_KEY) are intentionally
 * NOT written — they come from Google Secret Manager / a developer's own key.
 * Sending campaign email therefore stays disabled until a real key is provided.
 *
 * Idempotent and non-destructive: if `.env.local` already exists it is left
 * untouched so a developer's own secrets are never clobbered.
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const projectRoot = path.join(path.dirname(fileURLToPath(import.meta.url)), '..')
const appHostingPath = path.join(projectRoot, 'apphosting.yaml')
const envLocalPath = path.join(projectRoot, '.env.local')

// Only these non-secret keys are mirrored from apphosting.yaml into .env.local.
const WANTED_KEYS = new Set([
  'VITE_MS_TENANT_ID',
  'VITE_MS_CLIENT_ID',
  'FIREBASE_API_KEY',
  'FIREBASE_AUTH_DOMAIN',
  'FIREBASE_PROJECT_ID',
  'FIREBASE_STORAGE_BUCKET',
  'FIREBASE_MESSAGING_SENDER_ID',
  'FIREBASE_APP_ID',
  'SENDGRID_FROM_EMAIL',
  'SENDGRID_FROM_NAME',
  'SENDGRID_TEST_RECIPIENT',
])

function stripYamlScalar(raw) {
  const value = raw.trim()
  if (
    (value.startsWith("'") && value.endsWith("'")) ||
    (value.startsWith('"') && value.endsWith('"'))
  ) {
    return value.slice(1, -1)
  }
  return value
}

/** Parse the `env:` list of apphosting.yaml into { variable: value } pairs. */
function parseAppHostingEnv(yamlText) {
  const lines = yamlText.split(/\r?\n/)
  const result = {}
  let current = null
  for (const line of lines) {
    const variableMatch = line.match(/^\s*-\s*variable:\s*(.+)$/)
    if (variableMatch) {
      if (current && current.variable && current.value != null) {
        result[current.variable] = current.value
      }
      current = { variable: stripYamlScalar(variableMatch[1]), value: null }
      continue
    }
    if (!current) continue
    const valueMatch = line.match(/^\s*value:\s*(.+)$/)
    if (valueMatch) {
      current.value = stripYamlScalar(valueMatch[1])
    }
  }
  if (current && current.variable && current.value != null) {
    result[current.variable] = current.value
  }
  return result
}

function main() {
  if (fs.existsSync(envLocalPath)) {
    console.log('[gen-dev-env] .env.local already exists — leaving it untouched.')
    return
  }
  if (!fs.existsSync(appHostingPath)) {
    console.warn('[gen-dev-env] apphosting.yaml not found — skipping .env.local generation.')
    return
  }

  const parsed = parseAppHostingEnv(fs.readFileSync(appHostingPath, 'utf8'))
  const lines = [
    '# Auto-generated by .cursor/gen-dev-env.mjs from apphosting.yaml (non-secret values only).',
    '# Safe to edit or delete. Secret keys (OPENAI_API_KEY, SENDGRID_API_KEY) are intentionally omitted.',
    '',
    'VITE_MS_REDIRECT_URI=http://localhost:5173/auth/microsoft/callback',
  ]

  for (const key of WANTED_KEYS) {
    if (parsed[key]) {
      lines.push(`${key}=${parsed[key]}`)
    }
  }
  lines.push('')

  fs.writeFileSync(envLocalPath, lines.join('\n'), 'utf8')
  const projectId = parsed.FIREBASE_PROJECT_ID || '(unknown)'
  console.log(`[gen-dev-env] Wrote .env.local (Firebase project "${projectId}"). Secret keys omitted.`)
}

main()
